CREATE TABLE app_user (
 id uuid PRIMARY KEY, email varchar(254) NOT NULL UNIQUE, password_hash varchar(255) NOT NULL, name varchar(40) NOT NULL,
 created_at timestamptz, updated_at timestamptz
);
CREATE TABLE document_check (
 id uuid PRIMARY KEY, user_id uuid NOT NULL REFERENCES app_user(id), request_key uuid NOT NULL, title varchar(100) NOT NULL,
 document_type varchar(255) NOT NULL CHECK(document_type IN ('EMPLOYMENT','LEASE')),
 status varchar(255) NOT NULL CHECK(status IN ('PENDING','RUNNING','COMPLETED','PARTIAL','FAILED')),
 page_count integer NOT NULL CHECK(page_count BETWEEN 1 AND 10), archived boolean NOT NULL DEFAULT false,
 revision integer NOT NULL DEFAULT 1, previous_id uuid REFERENCES document_check(id), result_json text, failure_reason varchar(255),
 scenario varchar(255) NOT NULL, lock_version bigint NOT NULL DEFAULT 0, created_at timestamptz, updated_at timestamptz,
 UNIQUE(user_id,request_key), UNIQUE(previous_id)
);
CREATE INDEX document_user_created_idx ON document_check(user_id,created_at DESC);
CREATE TABLE contract_schedule (
 id uuid PRIMARY KEY,user_id uuid NOT NULL REFERENCES app_user(id),document_id uuid NOT NULL REFERENCES document_check(id),
 suggestion_key varchar(80) NOT NULL,title varchar(100) NOT NULL,date date NOT NULL,source varchar(40) NOT NULL,
 created_at timestamptz,updated_at timestamptz, UNIQUE(document_id,suggestion_key)
);
CREATE INDEX schedule_user_date_idx ON contract_schedule(user_id,date);
CREATE TABLE chat_session (
 id uuid PRIMARY KEY,user_id uuid NOT NULL REFERENCES app_user(id),document_id uuid REFERENCES document_check(id),created_at timestamptz,updated_at timestamptz
);
CREATE TABLE chat_message (
 id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,session_id uuid NOT NULL REFERENCES chat_session(id),request_key uuid NOT NULL,
 question text NOT NULL,answer text NOT NULL,created_at timestamptz,updated_at timestamptz,UNIQUE(session_id,request_key)
);
